"""DejaVu TrueType fonts bundled with matplotlib, used by every generated PDF and image.

The PDF core fonts (Helvetica, Times) only encode latin-1: they cannot print the euro sign or
"œ". PDFs therefore embed a subset of these Unicode fonts, and images draw text with them.
"""

from __future__ import annotations

import hashlib
from functools import cache
from pathlib import Path

import matplotlib
from PIL import ImageFont

FONT_DIR = Path(matplotlib.get_data_path()) / "fonts" / "ttf"
FONT_FILES = {
    "regular": "DejaVuSans.ttf",
    "bold": "DejaVuSans-Bold.ttf",
    "oblique": "DejaVuSans-Oblique.ttf",
    "bold-oblique": "DejaVuSans-BoldOblique.ttf",
}


def font_path(style: str = "regular") -> Path:
    path = FONT_DIR / FONT_FILES[style]
    if not path.is_file():
        raise FileNotFoundError(f"font not found: {path}")
    return path


@cache
def pil_font(size: int, style: str = "regular") -> ImageFont.FreeTypeFont:
    # basic layout everywhere: builds with complex-text layout (raqm) kern and shift the glyphs.
    return ImageFont.truetype(str(font_path(style)), size, layout_engine=ImageFont.Layout.BASIC)


def font_hashes() -> dict[str, str]:
    """sha256 of every font file; generated bytes depend on them (recorded in the manifest)."""
    return {
        name: hashlib.sha256(font_path(style).read_bytes()).hexdigest()
        for style, name in sorted(FONT_FILES.items(), key=lambda item: item[1])
    }
