PROVENANCE_ORDER: tuple[Provenance, ...] = (
    "native-text",
    "deterministic-table",
    "ocr",
    "model-description",
)
"""A sidecar's frontmatter provenance is the first of these among the cited content."""

PROVENANCE_NOTES: dict[str, str] = {
    "native-text": "native text",
    "deterministic-table": "parsed deterministically",
    "ocr": "recognised from pixels, not quote-verified",
    "model-description": "generated by a model, not verified against the source",
}
MAX_SIDECAR_ROWS = 500
"""Rows rendered in one table sidecar (the rest is summarised in a note)."""
_FULL_AREA = 0.9
_TABLE_REF_RE = re.compile(r"^(t\d{2,})(?:\s*[:/.#_]?\s*(r\d{4,}))?$")
_FIGURE_REF_RE = re.compile(r"^f\d{2,}$")
_ROW_LOCATORS = (XlsxRowsLocator, CsvRowsLocator, DocxTableLocator)


@dataclass
class _Selection:
    """What one sidecar shows: the union over the citations of its locator key."""

    blocks: list[Block] = field(default_factory=list)
    figures: list[Figure] = field(default_factory=list)
    tables: dict[str, set[int] | None] = field(default_factory=dict)
    provenances: set[str] = field(default_factory=set)

    def add_blocks(self, blocks: Sequence[Block]) -> None:
        known = {block.id for block in self.blocks}
        self.blocks += [block for block in blocks if block.id not in known]

    def add_figure(self, figure: Figure) -> None:
        if all(existing.id != figure.id for existing in self.figures):
            self.figures.append(figure)

    def add_rows(self, table_id: str, rows: set[int] | None) -> None:
        """Rows of a table shown in full (``None`` = every row)."""
        if table_id in self.tables and self.tables[table_id] is None:
            return
        if rows is None:
            self.tables[table_id] = None
        else:
            self.tables[table_id] = (self.tables.get(table_id) or set()) | rows

    def merge(self, other: _Selection) -> None:
        self.add_blocks(other.blocks)
        for figure in other.figures:
            self.add_figure(figure)
        for table_id, rows in other.tables.items():
            self.add_rows(table_id, rows)
        self.provenances |= other.provenances


@dataclass
class _Context:
    doc: ExtractedDoc
    title: str
    source_page_path: str
    sensitivity: Sensitivity
    original: str | None
    images: PageImages
    guard: TextGuard
    _embedded: dict[str, bytes] | None = None

    def embedded_figure(self, figure: Figure) -> bytes | None:
        """Picture of a DOCX/PPTX figure, re-read from the original with the same adapter."""
        if self._embedded is None:
            self._embedded = {}
            detected = detect_format(self.doc.source_path)
            data = self.images.raw()
            same_version = self.doc.extraction.adapter_version == ADAPTER_VERSION
            if detected and detected[0] in ("docx", "pptx") and data and same_version:
                draft = run_local_adapter(detected[0], detected[1], data, ExtractSettings())
                self._embedded = {
                    f"f{index:02d}": item.png for index, item in enumerate(draft.figures, 1)
                }
        return self._embedded.get(figure.id)


def _area(bbox: Sequence[float]) -> float:
    return (bbox[2] - bbox[0]) * (bbox[3] - bbox[1])


def _sort_key(key: str) -> tuple[int, int, int, int, str, int, int, str, int, str, int, str]:
    parts = parse_locator_key(key)
    return (
        LOCATOR_KINDS.index(parts.kind),
        parts.page or 0,
        parts.paragraph or 0,
        parts.table or 0,
        parts.sheet_slug or "",
        parts.row_start or 0,
        parts.slide or 0,
        parts.part or "",
        parts.line_start or 0,
        parts.cue_start or "",
        parts.region or 0,
        key,
    )


def _sheet_slug(locator: Locator) -> str | None:
    return parse_locator_key(locator_key(locator)).sheet_slug


def _canonical(locators: Sequence[Locator], guard: TextGuard) -> Locator:
    """The locator written in the sidecar frontmatter (one per key, canaries redacted)."""
    first = locators[0]
    if isinstance(first, PdfPageLocator):
        return PdfPageLocator(page=first.page)
    if isinstance(first, PptxSlideLocator):
        return PptxSlideLocator(slide=first.slide)
    if isinstance(first, ImageRegionLocator):
        boxes = [loc.bbox for loc in locators if isinstance(loc, ImageRegionLocator)]
        union = round_bbox(
            (
                min(b[0] for b in boxes),
                min(b[1] for b in boxes),
                max(b[2] for b in boxes),
                max(b[3] for b in boxes),
            )
        )
        return ImageRegionLocator(region=first.region, bbox=union or list(first.bbox))
    if isinstance(first, VttCueLocator):
        ends = [loc.cue_end for loc in locators if isinstance(loc, VttCueLocator)]
        last = max(ends, key=lambda cue: tuple(int(part) for part in cue.split(":")))
        return VttCueLocator(cue_start=first.cue_start, cue_end=last)
    if isinstance(first, XlsxRowsLocator):
        sheet = guard.redact(first.sheet)
        update: dict[str, object] = {"cols": None}
        if sheet != first.sheet:  # keep the key: pin the slug derived from the real name
            update |= {"sheet": sheet, "sheet_slug": _sheet_slug(first)}
        return first.model_copy(update=update)
    return first


def _same_table(locator: Locator, candidate: Locator) -> bool:
    if isinstance(locator, XlsxRowsLocator) and isinstance(candidate, XlsxRowsLocator):
        return _sheet_slug(candidate) == _sheet_slug(locator)
    if isinstance(locator, DocxTableLocator) and isinstance(candidate, DocxTableLocator):
        return candidate.table == locator.table
    return isinstance(locator, CsvRowsLocator) and isinstance(candidate, CsvRowsLocator)


def _table_for(doc: ExtractedDoc, locator: Locator) -> Table | None:
    return next((table for table in doc.tables if _same_table(locator, table.locator)), None)


def _figure_matches(figure: Figure, locator: Locator) -> bool:
    """True when ``locator`` designates the figure (figure locator, or its page + bbox)."""
    if figure.locator == locator:
        return True
    return (
        isinstance(locator, PdfPageLocator)
        and isinstance(figure.locator, PdfPageLocator)
        and locator.page == figure.locator.page
        and locator.bbox is not None
        and locator.bbox == (figure.locator.bbox or figure.bbox)
    )


def _resolve(
    doc: ExtractedDoc,
    key: str,
    item: CitedLocator,
    keyed: Sequence[Block],
    blocks: Mapping[str, Block],
) -> _Selection:
    """What one citation shows: its blocks, table rows and figures.

    ``block_ids`` may hold block ids (``b0042``), table refs (``t03``, ``t03:r0012``) and
    figure refs (``f02``). Every cited block is shown, also the blocks of other locator keys (a
    quote that runs across paragraphs is cited by the locator of its first block). Without
    block ids the locator decides: a figure locator shows the figure, a table locator that is
    not a row range (PDF and PPTX tables) shows the table, otherwise the blocks of the key with
    the citation's provenance are shown. Row-range locators (XLSX, CSV, DOCX tables) always
    render their rows (see :func:`_rows_section`).
    """
    selection = _Selection()
    refs = [ref.strip().lower() for ref in item.block_ids]
    explicit = [blocks[ref] for ref in dict.fromkeys(refs) if ref in blocks]
    selection.add_blocks(explicit)
    selection.provenances |= {block.provenance for block in explicit}
    tables = {table.id: table for table in doc.tables}
    figures = {figure.id: figure for figure in doc.figures if locator_key(figure.locator) == key}
    cited_table = False
    for ref in refs:
        table_ref = _TABLE_REF_RE.match(ref)
        if table_ref and table_ref[1] in tables:
            table = tables[table_ref[1]]
            cited_table = True
            selection.provenances.add(table.provenance)
            if not isinstance(table.locator, _ROW_LOCATORS) and locator_key(table.locator) == key:
                selection.add_rows(table.id, {int(table_ref[2][1:])} if table_ref[2] else None)
        elif _FIGURE_REF_RE.match(ref) and ref in figures:
            figure = figures[ref]
            selection.add_figure(figure)
            selection.provenances.add(
                "model-description" if figure.description else item.provenance
            )
    for table in tables.values():
        if (
            not isinstance(table.locator, _ROW_LOCATORS)
            and table.locator == item.locator
            and table.id not in selection.tables
        ):
            cited_table = True
            selection.add_rows(table.id, None)
            selection.provenances.add(table.provenance)
    for figure in figures.values():
        if _figure_matches(figure, item.locator):
            selection.add_figure(figure)
            selection.provenances.add(item.provenance)
    if not explicit and not selection.figures and not cited_table:
        available = {block.provenance for block in keyed}
        if item.provenance in available:
            selection.add_blocks([b for b in keyed if b.provenance == item.provenance])
            selection.provenances.add(item.provenance)
        else:
            selection.add_blocks(keyed)
            selection.provenances |= available or {item.provenance}
    return selection


def _select(ctx: _Context, key: str, items: Sequence[CitedLocator], locator: Locator) -> _Selection:
    keyed = [block for block in ctx.doc.blocks if block.locator_key == key]
    blocks = {block.id: block for block in ctx.doc.blocks}
    selection = _Selection()
    for item in items:
        selection.merge(_resolve(ctx.doc, key, item, keyed, blocks))
    order = {block.id: index for index, block in enumerate(ctx.doc.blocks)}
    selection.blocks.sort(key=lambda block: order[block.id])
    figure_order = {figure.id: index for index, figure in enumerate(ctx.doc.figures)}
    selection.figures.sort(key=lambda figure: figure_order[figure.id])
    if isinstance(locator, _ROW_LOCATORS):
        table = _table_for(ctx.doc, locator)
        if table is not None:  # row ranges always show the rows of their table
            selection.provenances = {table.provenance} | (
                selection.provenances & {"model-description"}
            )
    if not selection.provenances:
        selection.provenances = {item.provenance for item in items}
    return selection


def _md_table(columns: Sequence[str], cells: Sequence[str] | None) -> list[str]:
    lines = [
        "| " + " | ".join(table_cell(column) for column in columns) + " |",
        "| " + " | ".join("---" for _ in columns) + " |",
    ]
    if cells is not None:
        lines.append("| " + " | ".join(table_cell(cell) for cell in cells) + " |")
    return lines


def _rows_section(ctx: _Context, locator: Locator) -> list[str]:
    if not isinstance(locator, _ROW_LOCATORS):
        return []
    table = _table_for(ctx.doc, locator)
    if table is None:
        return []
    guard = ctx.guard
    columns = [guard(column) for column in table.columns]
    rows = {int(row.row_id[1:]): row.cells for row in table.rows}
    numbers = sorted(n for n in rows if locator.row_start <= n <= locator.row_end)
    if locator.row_start == 1:
        numbers.insert(0, 1)
    lines: list[str] = []
    for shown, number in enumerate(numbers):
        if shown == MAX_SIDECAR_ROWS:
            lines += [f"Rows {number} and later are not shown (limit {MAX_SIDECAR_ROWS}).", ""]
            break
        cells = None if number == 1 else [guard(cell) for cell in rows[number]]
        lines += [f"## Row {number}", "", *_md_table(columns, cells), ""]
    return lines


def _tables_section(ctx: _Context, tables: Mapping[str, set[int] | None]) -> list[str]:
    """Cited tables that are not row ranges (PDF and PPTX tables): their cited rows."""
    lines: list[str] = []
    guard = ctx.guard
    for table_id in sorted(tables):
        table = ctx.doc.table(table_id)
        wanted = tables[table_id]
        rows = [row for row in table.rows if wanted is None or int(row.row_id[1:]) in wanted]
        header = ["Row", *(guard(column) for column in table.columns)]
        lines += [
            f"## Table {table_id}",
            "",
            "| " + " | ".join(table_cell(cell) for cell in header) + " |",
            "| " + " | ".join("---" for _ in header) + " |",
        ]
        for row in rows[:MAX_SIDECAR_ROWS]:
            cells = [str(int(row.row_id[1:])), *(guard(cell) for cell in row.cells)]
            lines.append("| " + " | ".join(table_cell(cell) for cell in cells) + " |")
        lines.append("")
        if len(rows) > MAX_SIDECAR_ROWS:
            lines += [f"{len(rows) - MAX_SIDECAR_ROWS} more rows are not shown.", ""]
    return lines


def _text_section(ctx: _Context, key: str, blocks: Sequence[Block]) -> list[str]:
    """Native text, quoted; each block is labelled when they come from several locators."""
    lines = ["## Text", ""]
    labelled = any(block.locator_key != key for block in blocks)
    first = True
    for block in blocks:
        quoted = quote_block(ctx.guard(block.text))
        if not quoted:
            continue
        if not first:
            lines.append(">")
        first = False
        if labelled or isinstance(block.locator, VttCueLocator):
            lines.append(f"> **{escape_text(locator_label(block.locator))}**\\")
        if block.kind == "note":
            lines.append("> *Speaker notes*\\")
        lines += quoted
    return [*lines, ""] if not first else []


def _same_image(locator: Locator, other: Locator) -> bool:
    """True when both locators lie on the same page image (PDF page or image file)."""
    if isinstance(locator, PdfPageLocator) and isinstance(other, PdfPageLocator):
        return locator.page == other.page
    return isinstance(locator, ImageRegionLocator) and isinstance(other, ImageRegionLocator)


def _block_image(
    ctx: _Context, block: Block, locator: Locator, image: bytes | None
) -> bytes | None:
    """The page image a block lies on (``image`` when it is the sidecar's own page)."""
    if _same_image(block.locator, locator):
        return image
    if isinstance(block.locator, PdfPageLocator | ImageRegionLocator):
        return ctx.images.get(block.locator.page)
    return None


def _ocr_section(
    ctx: _Context, key: str, locator: Locator, blocks: Sequence[Block], image: bytes | None
) -> tuple[list[str], list[tuple[str, bytes]]]:
    lines = ["## OCR text", ""]
    assets: list[tuple[str, bytes]] = []
    labelled = any(block.locator_key != key for block in blocks)
    for block in blocks:
        if labelled:
            lines += [f"**{escape_text(locator_label(block.locator))}**", ""]
        bbox = getattr(block.locator, "bbox", None)
        source = _block_image(ctx, block, locator, image) if bbox else None
        if source is not None and bbox and _area(bbox) < _FULL_AREA:
            crop = crop_png(source, bbox)
            if crop is not None:
                name = f"img/{key}-{block.id}.png"
                assets.append((name, crop))
                lines += [f"![Crop of {block.id}]({name})", ""]
        quoted = quote_block(ctx.guard(block.text))
        if quoted:
            lines += [*quoted, ""]
        else:
            lines += ["No text was recognised here: local extraction does not run OCR.", ""]
        confidence = "not reported" if block.confidence is None else f"{block.confidence:.2f}"
        lines += [f"OCR confidence: {confidence}", ""]
    return lines, assets


def _figure_image(ctx: _Context, figure: Figure) -> bytes | None:
    locator = figure.locator
    bbox = figure.bbox or getattr(locator, "bbox", None)
    if isinstance(locator, PdfPageLocator | ImageRegionLocator) and bbox:
        page_image = ctx.images.get(locator.page)
        return crop_png(page_image, bbox) if page_image else None
    return ctx.embedded_figure(figure)


def _figures_section(
    ctx: _Context, key: str, figures: Sequence[Figure]
) -> tuple[list[str], list[tuple[str, bytes]]]:
    lines: list[str] = []
    assets: list[tuple[str, bytes]] = []
    for figure in figures:
        lines += [f"## Figure {figure.id}", ""]
        image = _figure_image(ctx, figure)
        if image is not None:
            name = f"img/{key}-{figure.id}.png"
            assets.append((name, image))
            lines += [f"![Figure {figure.id}]({name})", ""]
        if figure.caption:
            lines += [f"Caption: {escape_text(ctx.guard(figure.caption))}", ""]
        if figure.description:
            lines += [
                "> **Generated description** — written by a model from the figure image; not "
                "verified against the source.",
                ">",
                *quote_block(ctx.guard(figure.description)),
                "",
            ]
    return lines, assets


def _header(ctx: _Context, path: str, locator: Locator, primary: str, provenances: set[str]) -> str:
    link = relative_link(path, ctx.source_page_path)
    parts = [f"Source page: [{escape_text(ctx.title)}]({link})"]
    if ctx.original:
        if isinstance(locator, PdfPageLocator):
            label = f"{ctx.original}, p. {locator.page}"
            parts.append(f"Original file: [{label}]({ctx.original}#page={locator.page})")
        else:
            parts.append(f"Original file: [{ctx.original}]({ctx.original})")
    parts.append(f"Provenance: {badge_for(primary)} ({PROVENANCE_NOTES[primary]})")
    if "model-description" in provenances and primary != "model-description":
        parts.append("Figures: generated description (model output, not verified)")
    return " · ".join(parts)


def _sidecar(
    ctx: _Context, key: str, items: Sequence[CitedLocator]
) -> tuple[EvidencePage, list[tuple[str, bytes]], str]:
    sid = ctx.doc.source_id
    path = evidence_path(sid, key)
    locator = _canonical([item.locator for item in items], ctx.guard)
    label = locator_label(locator)
    selection = _select(ctx, key, items, locator)
    provenances = selection.provenances
    primary = next(p for p in PROVENANCE_ORDER if p in provenances)
    title = f"{ctx.title} — {label}"
    assets: list[tuple[str, bytes]] = []
    lines = [
        f"# {escape_text(title)}",
        "",
        _header(ctx, path, locator, primary, provenances),
        "",
    ]

    image: bytes | None = None
    if isinstance(locator, PdfPageLocator | ImageRegionLocator):
        image = ctx.images.get(locator.page)
        if image is not None:
            boxes = [
                bbox
                for bbox in (
                    *(getattr(item.locator, "bbox", None) for item in items),
                    *(
                        getattr(block.locator, "bbox", None)
                        for block in selection.blocks
                        if _same_image(block.locator, locator)
                    ),
                    *(figure.bbox for figure in selection.figures),
                )
                if bbox and _area(bbox) < _FULL_AREA
            ]
            name = f"img/{key}.png"
            assets.append((name, draw_highlights(image, boxes)))
            what = f"Page {locator.page}" if isinstance(locator, PdfPageLocator) else "Image"
            alt = f"{what} of {ctx.title}"
            if boxes:
                alt += " with the cited regions highlighted"
            lines += [f"![{escape_text(alt)}]({name})", ""]

    body_start = len(lines)
    native = [b for b in selection.blocks if b.provenance == "native-text"]
    lines += _text_section(ctx, key, native)
    ocr_blocks = [b for b in selection.blocks if b.provenance == "ocr"]
    if ocr_blocks:
        ocr_lines, ocr_assets = _ocr_section(ctx, key, locator, ocr_blocks, image)
        lines += ocr_lines
        assets += ocr_assets
    lines += _rows_section(ctx, locator)
    lines += _tables_section(ctx, selection.tables)
    if selection.figures:
        figure_lines, figure_assets = _figures_section(ctx, key, selection.figures)
        lines += figure_lines
        assets += figure_assets
    if len(lines) == body_start:
        lines += ["No extracted content is available for this locator.", ""]

    body = sanitize_markdown("\n".join(lines).rstrip("\n") + "\n", allow_markers=False)[0]
    frontmatter = EvidenceFrontmatter(
        id=f"evidence:{sid}:{key}",
        title=plain_text(title) or key,
        source_id=sid,
        locator=locator,
        provenance=primary,
        sensitivity=ctx.sensitivity,
    )
    asset_paths = [(f"{EVIDENCE_MOUNT}/{sid}/{name}", data) for name, data in assets]
    return EvidencePage(path=path, frontmatter=frontmatter, body=body), asset_paths, primary


def _index(ctx: _Context, entries: Sequence[tuple[str, str, str]]) -> EvidencePage:
    sid = ctx.doc.source_id
    path = evidence_index_path(sid)
    link = relative_link(path, ctx.source_page_path)
    source = f"Source page: [{escape_text(ctx.title)}]({link})"
    if ctx.original:
        source += f" · Original file: [{ctx.original}]({ctx.original})"
    title = f"Evidence for {ctx.title}"
    lines = [f"# {escape_text(title)}", "", source, "", "## Locators", ""]
    if entries:
        lines += [
            f"- [{escape_text(label)}]({key}.md) · {badge_for(provenance)}"
            for key, label, provenance in entries
        ]
    else:
        lines.append("No locator of this source is cited.")
    body = sanitize_markdown("\n".join(lines) + "\n", allow_markers=False)[0]
    frontmatter = EvidenceIndexFrontmatter(
        id=f"evidence:{sid}",
        title=plain_text(title) or f"Evidence for {sid}",
        source_id=sid,
        sensitivity=ctx.sensitivity,
    )
    return EvidencePage(path=path, frontmatter=frontmatter, body=body)


def _original_name(source_path: str) -> str:
    """``original.<ext>``; a Markdown source is published as ``original.txt``.

    Every ``.md`` file under ``evidence/`` is read as a page (the frontmatter gate G01, Quartz,
    the MCP evidence listing), so a verbatim Markdown original keeps its bytes but not its
    extension: it is served as plain text, never rendered.
    """
    extension = PurePosixPath(source_path).suffix.lower().lstrip(".")
    if not re.fullmatch(r"[a-z0-9]{1,10}", extension):
        extension = "bin"
    return f"original.{_TEXT_EXTENSIONS.get(extension, extension)}"


# Page extensions published under a plain-text name (see :func:`_original_name`).
_TEXT_EXTENSIONS = {"md": "txt", "markdown": "txt"}

# Originals the release validator reads as text (gate G05 scans .md and .txt files).
_SCANNED_ORIGINALS = (".md", ".txt")


def _unsafe_text_original(name: str, data: bytes) -> str | None:
    """Why a verbatim ``original.md``/``original.txt`` would fail gate G05, else ``None``.

    Originals are byte-identical copies, so they cannot be escaped like sidecars: one with a
    bare URL or e-mail, raw HTML or another unsafe construct is withheld instead.
    """
    if not name.endswith(_SCANNED_ORIGINALS):
        return None
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return None  # the validator skips text it cannot decode as well
    problems = find_violations(text, allow_markers=False)
    return problems[0].kind if problems else None


def _spanned(doc: ExtractedDoc, cited: Sequence[CitedLocator]) -> list[CitedLocator]:
    """One citation per other locator key of the blocks each citation names, in citation order.

    A citation of several blocks carries the locator of its first block; its other blocks also
    get the sidecars of their own locators, showing those blocks.
    """
    blocks = {block.id: block for block in doc.blocks}
    spanned: list[CitedLocator] = []
    for item in cited:
        by_key: dict[str, list[Block]] = {}
        for ref in dict.fromkeys(ref.strip().lower() for ref in item.block_ids):
            block = blocks.get(ref)
            if block is not None and block.locator_key != item.key:
                by_key.setdefault(block.locator_key, []).append(block)
        spanned.extend(
            CitedLocator(
                source_id=item.source_id,
                locator=found[0].locator,
                block_ids=tuple(block.id for block in found),
                quotes=item.quotes,
                provenance=found[0].provenance,
            )
            for found in by_key.values()
        )
    return spanned


def build_evidence(
    *,
    doc: ExtractedDoc,
    raw_file: Path,
    cited: Sequence[CitedLocator],
    source_title: str,
    source_page_path: str,
    sensitivity: Sensitivity,
    publish_original: bool,
    writer: ReleaseWriter,
    page_images: Mapping[int, bytes] | None = None,
    canaries: Sequence[str] = (),
) -> list[str]:
    """Write the evidence of one source and return the written release paths (sorted).

    ``cited`` are the locators cited by pages (all of ``doc.source_id``); one sidecar is
    written per distinct locator key, and per other locator key of the blocks a citation names
    (a quote running across paragraphs is cited by its first block's locator: that sidecar
    shows every cited block and the other blocks get their own sidecars too).
    ``source_page_path`` is the source page path in the content namespace
    (``sources/<slug>.md``). ``page_images`` are the extract stage's page renders; missing PDF
    pages are rendered from ``raw_file`` at 150 dpi. ``canaries`` are never rendered
    (case-insensitive) and an original containing one is not published; neither is a text
    original that would fail the safe-content gate (G05), such as one with a bare e-mail.
    """
    sid = doc.source_id
    groups: dict[str, list[CitedLocator]] = {}
    for item in cited:
        if item.source_id != sid:
            raise ValueError(f"cited locator of {item.source_id} passed for source {sid}")
        groups.setdefault(item.key, []).append(item)
    for item in _spanned(doc, cited):
        groups.setdefault(item.key, []).append(item)

    guard = TextGuard(canaries)
    title = (
        guard(one_line(source_title))
        or guard(one_line(doc.title_hint or ""))
        or PurePosixPath(doc.source_path).stem
        or sid
    )
    raw_path = Path(raw_file)
    images = PageImages(doc, raw_path, page_images)
    original = _original_name(doc.source_path) if publish_original else None
    if original and guard.contains_canary(images.raw() or b""):
        logger.warning("evidence %s: original not published (it contains a canary string)", sid)
        original = None
    unsafe = _unsafe_text_original(original, images.raw() or b"") if original else None
    if unsafe:
        logger.warning("evidence %s: original not published (unsafe as text: %s)", sid, unsafe)
        original = None
    ctx = _Context(
        doc=doc,
        title=title,
        source_page_path=source_page_path,
        sensitivity=sensitivity,
        original=original,
        images=images,
        guard=guard,
    )
    written: set[str] = set()
    if original:
        written.add(writer.copy_file(f"{EVIDENCE_MOUNT}/{sid}/{original}", raw_path))
    entries: list[tuple[str, str, str]] = []
    for key in sorted(groups, key=_sort_key):
        page, assets, primary = _sidecar(ctx, key, groups[key])
        for rel_path, data in assets:
            written.add(writer.write_bytes(rel_path, data))
        written.add(writer.write_evidence(page))
        frontmatter = page.frontmatter
        assert isinstance(frontmatter, EvidenceFrontmatter)
        entries.append((key, locator_label(frontmatter.locator), primary))
    written.add(writer.write_evidence(_index(ctx, entries)))
    if guard.neutralized or guard.redacted:
        logger.warning(
            "evidence %s: %d sentence(s) addressed to AI systems replaced, %d canary string(s) "
            "redacted",
            sid,
            guard.neutralized,
            guard.redacted,
        )
    return sorted(written)
