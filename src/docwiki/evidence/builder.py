"""``build_evidence``: sidecars for cited locators, the per-source evidence index, images.

One sidecar per distinct locator key (``evidence/<source_id>/<locator_key>.md``), rendered from
the ExtractedDoc only (never from model output except clearly labelled figure descriptions):

* page/region locators (PDF, images) show the page image with highlight boxes for every cited
  bbox (``img/<key>.png``);
* native text is quoted verbatim, OCR text comes with its crop and confidence, table rows are
  rendered under ``## Row N`` headings, figures show the image and the generated description;
* citations are resolved one by one — block ids (``b0042``), table refs (``t03``,
  ``t03:r0012``) and figure refs (``f02``) in ``block_ids``, or, when ``block_ids`` is empty,
  the cited locator itself (narrowed table row ranges, figure locators);
* a citation of several blocks (a quote running across paragraphs, carried by the locator of
  its first block) shows every cited block, each labelled with its locator; the blocks of other
  locator keys also get their own sidecars;
* every document-derived string goes through the :class:`~docwiki.evidence.guard.TextGuard`
  (canaries redacted, sentences addressed to AI systems replaced) and is escaped
  (:mod:`docwiki.evidence.escape`).
"""

