import { FullSlug, resolveRelative } from "../../util/path"
import { classNames } from "../../util/lang"
import { QuartzComponent, QuartzComponentConstructor, QuartzComponentProps } from "../types"
import { settings } from "./settings"

/** "About DocWiki" landing section, rendered on the home page only. */
export default (() => {
  const About: QuartzComponent = ({ fileData, displayClass }: QuartzComponentProps) => {
    if (fileData.slug !== "index") return null
    const llms = resolveRelative(fileData.slug as FullSlug, "llms.txt" as FullSlug)
    return (
      <section
        class={classNames(displayClass, "docwiki-about")}
        aria-labelledby="docwiki-about-title"
      >
        <h2 id="docwiki-about-title">About DocWiki</h2>
        <p>
          This site was generated by DocWiki, which compiles a folder of documents (PDF, Word,
          Excel, CSV, PowerPoint, e-mail, scans and transcripts) into a Markdown wiki that people
          can browse and agents can trust.
        </p>
        <ul>
          <li>
            Every fact ends with a footnote that opens its evidence: the exact page, paragraph or
            table rows it came from, with a provenance badge.
          </li>
          <li>
            Contradictions between documents and superseded revisions are shown side by side, never
            silently resolved.
          </li>
          <li>
            The same immutable release ships as plain Markdown for agents, with an{" "}
            <a href={llms}>llms.txt</a> index, an agent guide and skills.
          </li>
        </ul>
        <p>
          <a href={settings.repoUrl}>Source code and documentation</a>
        </p>
      </section>
    )
  }

  return About
}) satisfies QuartzComponentConstructor
