import { FullSlug, resolveRelative } from "../../util/path"
import { classNames } from "../../util/lang"
import { QuartzComponent, QuartzComponentConstructor, QuartzComponentProps } from "../types"
import { documentsPhrase, qualityPhrase } from "../../plugins/transformers/docwiki-text"
import { settings } from "./settings"
import { WIKI_ANCHOR } from "./Story"

/**
 * "About this wiki" block of the home page, under the story strip (Story.tsx): how the release was
 * built (documents, release date, quality gates, run receipt, quality report) and a collapsible
 * "About DocWiki". A visually hidden "The wiki" heading follows: the wiki's own home page starts
 * there, and the strip's third card leads to it.
 */
export default (() => {
  const About: QuartzComponent = ({ fileData, displayClass }: QuartzComponentProps) => {
    if (fileData.slug !== "index") return null
    const slug = fileData.slug as FullSlug
    const link = (target: string) => resolveRelative(slug, target as FullSlug)
    const llms = link("llms.txt")
    const { documents, quality } = settings
    return (
      <>
        <section class={classNames(displayClass, "docwiki-about")} aria-label="About this wiki">
          <p class="docwiki-provenance">
            Compiled by <a href={settings.repoUrl}>DocWiki</a> from{" "}
            {documentsPhrase(documents.current, documents.superseded)}
            {settings.releaseDate && <> · release {settings.releaseDate}</>}
            {quality && <> · quality gates: {qualityPhrase(quality)}</>}
            {settings.runPage && (
              <>
                {" · "}
                <a href={link(settings.runPage)}>run receipt</a>
              </>
            )}
            {settings.qualityPage && (
              <>
                {" · "}
                <a href={link(settings.qualityPage)}>quality report</a>
              </>
            )}
            {" · "}
            <a href={link("pipeline")}>the pipeline</a>
          </p>
          <details class="docwiki-about-more">
            <summary>About DocWiki</summary>
            <p>
              This site was generated by DocWiki, which compiles a folder of documents (PDF, Word,
              Excel, CSV, PowerPoint, e-mail, scans and transcripts) into a Markdown wiki that
              people can browse and agents can trust.
            </p>
            <ul>
              <li>
                Every fact ends with a footnote that opens its evidence: the exact page, paragraph
                or table rows it came from, with a provenance badge.
              </li>
              <li>
                Contradictions between documents and superseded revisions are shown side by side,
                never silently resolved.
              </li>
              <li>
                The same immutable release ships as plain Markdown for agents, with an{" "}
                <a href={llms}>llms.txt</a> index, an agent guide and skills.
              </li>
            </ul>
            <p>
              <a class="docwiki-target" href={settings.repoUrl}>
                Source code and documentation
              </a>
            </p>
          </details>
        </section>
        <h2 id={WIKI_ANCHOR} class="sr-only" tabIndex={-1}>
          The wiki
        </h2>
      </>
    )
  }

  return About
}) satisfies QuartzComponentConstructor
